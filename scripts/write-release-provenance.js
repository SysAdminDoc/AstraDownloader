#!/usr/bin/env node
'use strict';

// Release provenance: a PEP 751 lock file and a CycloneDX SBOM beside the
// binary.
//
// The license inventory already knows what is inside the executable, but it
// emits bare component/dependency arrays — not a document any standard tool
// will read, and not one that satisfies CISA's 2026 Minimum Elements for an
// SBOM (published 2026-07-29), which added component hash, licence, tool name
// and generation context to the required fields. This wraps the same data in a
// CycloneDX 1.6 envelope and resolves the pinned Python graph into a
// `pylock.toml` that pip 26.1+ can install directly.
//
// Both outputs are release artifacts: they describe one exact build, so they
// are written next to it and validated against its digest rather than being
// regenerated from whatever happens to be installed later.

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const {
    COMPANION_EXE_NAME,
    PROPERTY,
    buildCompanionInventory,
    propertyValue,
    sha256
} = require('./companion-license-inventory');

const ROOT = path.join(__dirname, '..');
const BUILD_DIR = path.join(ROOT, 'build');
const CONSTRAINTS = path.join(ROOT, 'astra_downloader', 'constraints-release.txt');
const SBOM_NAME = 'astra-downloader-sbom.cdx.json';
const LOCK_NAME = 'pylock.toml';
const CYCLONEDX_SPEC = '1.6';
// pip's own cooldown vocabulary. A package published inside this window has
// not yet had time to be caught and yanked, which is when typosquats and
// compromised-maintainer releases are normally found.
const RESOLVE_COOLDOWN = 'P3D';

function readConstraints(constraintsPath = CONSTRAINTS) {
    const pins = [];
    for (const line of fs.readFileSync(constraintsPath, 'utf8').split(/\r?\n/)) {
        const text = line.trim();
        if (!text || text.startsWith('#')) continue;
        const match = text.match(/^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;#]+)/);
        if (match) pins.push({ name: match[1], version: match[2] });
    }
    return pins;
}

async function resolveFromPyPI(pin) {
    // A lock file without hashes is a wish list: pip cannot verify anything it
    // installs from it. Resolve each pin to its published artifacts and carry
    // their digests.
    const url = `https://pypi.org/pypi/${encodeURIComponent(pin.name)}/${encodeURIComponent(pin.version)}/json`;
    const response = await fetch(url, { headers: { accept: 'application/json' } });
    if (!response.ok) {
        throw new Error(`PyPI returned ${response.status} for ${pin.name}==${pin.version}`);
    }
    const payload = await response.json();
    const wheels = [];
    let sdist = null;
    for (const file of payload.urls || []) {
        if (file.yanked) continue;
        const digest = file.digests && file.digests.sha256;
        if (!digest) continue;
        if (file.packagetype === 'bdist_wheel') {
            wheels.push({ name: file.filename, url: file.url, sha256: digest, uploaded: file.upload_time_iso_8601 });
        } else if (file.packagetype === 'sdist' && !sdist) {
            sdist = { name: file.filename, url: file.url, sha256: digest, uploaded: file.upload_time_iso_8601 };
        }
    }
    if (!wheels.length && !sdist) {
        throw new Error(`no verifiable artifact published for ${pin.name}==${pin.version}`);
    }
    return { ...pin, wheels, sdist };
}

function tomlString(value) {
    return `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

function renderPylock(packages, generatedAt) {
    const lines = [
        '# Generated by scripts/write-release-provenance.js. Do not edit by hand.',
        '# PEP 751 lock for the reviewed Windows release graph. Regenerate with',
        '#   npm run release:provenance',
        'lock-version = "1.0"',
        `created-by = ${tomlString('astra-downloader')}`,
        'requires-python = ">=3.11"',
        `# generated: ${generatedAt}`,
        `# resolve-cooldown: ${RESOLVE_COOLDOWN}`,
        '',
    ];
    for (const pkg of packages) {
        lines.push('[[packages]]');
        lines.push(`name = ${tomlString(pkg.name)}`);
        lines.push(`version = ${tomlString(pkg.version)}`);
        for (const wheel of pkg.wheels) {
            lines.push('');
            lines.push('[[packages.wheels]]');
            lines.push(`name = ${tomlString(wheel.name)}`);
            lines.push(`url = ${tomlString(wheel.url)}`);
            lines.push('hashes = { sha256 = ' + tomlString(wheel.sha256) + ' }');
        }
        if (pkg.sdist) {
            lines.push('');
            lines.push('[packages.sdist]');
            lines.push(`name = ${tomlString(pkg.sdist.name)}`);
            lines.push(`url = ${tomlString(pkg.sdist.url)}`);
            lines.push('hashes = { sha256 = ' + tomlString(pkg.sdist.sha256) + ' }');
        }
        lines.push('');
    }
    return lines.join('\n');
}

function buildCycloneDx(inventory, artifact, generatedAt) {
    // CISA's 2026 minimum elements, mapped onto CycloneDX 1.6:
    //   supplier/author  -> metadata.supplier + metadata.authors
    //   timestamp        -> metadata.timestamp
    //   tool name        -> metadata.tools.components
    //   component hash   -> metadata.component.hashes and each component's
    //                       astra:companion:downloadSha256 property
    //   licence          -> component.licenses (already carried)
    //   unique id        -> bom-ref/purl (already carried) + serialNumber
    //   dependencies     -> dependencies graph (already carried)
    //   generation ctx   -> metadata.properties
    return {
        bomFormat: 'CycloneDX',
        specVersion: CYCLONEDX_SPEC,
        // Deterministic per artifact rather than random: re-running the
        // generator for the same build must not mint a new document identity.
        serialNumber: `urn:uuid:${uuidFromDigest(artifact.sha256)}`,
        version: 1,
        metadata: {
            timestamp: generatedAt,
            tools: {
                components: [{
                    type: 'application',
                    name: 'write-release-provenance',
                    version: readPackageVersion(),
                }],
            },
            authors: [{ name: 'SysAdminDoc' }],
            supplier: { name: 'SysAdminDoc', url: ['https://github.com/SysAdminDoc/AstraDownloader'] },
            component: {
                type: 'application',
                'bom-ref': `pkg:generic/AstraDownloader@${readPackageVersion()}`,
                name: 'Astra Downloader',
                version: readPackageVersion(),
                purl: `pkg:generic/AstraDownloader@${readPackageVersion()}`,
                hashes: [{ alg: 'SHA-256', content: artifact.sha256 }],
                licenses: [{ license: { id: 'MIT' } }],
            },
            properties: [
                { name: 'astra:release:artifact', value: artifact.name },
                { name: 'astra:release:resolveCooldown', value: RESOLVE_COOLDOWN },
                { name: 'astra:release:generationContext', value: 'local unsigned release build' },
            ],
        },
        components: inventory.components,
        dependencies: inventory.dependencies,
    };
}

function uuidFromDigest(digest) {
    const hex = String(digest).replace(/[^0-9a-f]/gi, '').padEnd(32, '0').slice(0, 32);
    return [
        hex.slice(0, 8), hex.slice(8, 12),
        `4${hex.slice(13, 16)}`,
        `8${hex.slice(17, 20)}`,
        hex.slice(20, 32),
    ].join('-');
}

let cachedVersion = null;
function readPackageVersion() {
    if (!cachedVersion) {
        cachedVersion = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version;
    }
    return cachedVersion;
}

/** Does this SBOM describe the artifact currently staged in build/? */
function sbomDescribesArtifact(sbom, artifactSha256) {
    const hashes = (sbom && sbom.metadata && sbom.metadata.component && sbom.metadata.component.hashes) || [];
    const declared = hashes.find((hash) => hash.alg === 'SHA-256');
    if (!declared || declared.content !== artifactSha256) return false;
    // Every inventoried component is stamped with the artifact it belongs to,
    // so a stale SBOM cannot be paired with a fresh binary.
    return (sbom.components || []).every(
        (component) => propertyValue(component, PROPERTY.artifactSha256) === artifactSha256
    );
}

async function writeReleaseProvenance(buildDir = BUILD_DIR, options = {}) {
    const repoRoot = options.repoRoot || ROOT;
    const constraintsPath = options.constraintsPath || CONSTRAINTS;
    const resolvePin = options.resolvePin || resolveFromPyPI;
    const inventoryBuilder = options.inventoryBuilder || buildCompanionInventory;
    const generatedAt = options.generatedAt || new Date().toISOString();
    const exePath = path.join(buildDir, COMPANION_EXE_NAME);
    const artifactSha256 = sha256(exePath);
    const inventory = inventoryBuilder(repoRoot, buildDir);

    const sbom = buildCycloneDx(inventory, { name: COMPANION_EXE_NAME, sha256: artifactSha256 }, generatedAt);
    if (!sbomDescribesArtifact(sbom, artifactSha256)) {
        throw new Error('generated SBOM does not describe the staged artifact');
    }

    // Resolve the complete lock in memory before touching either output. A
    // failed registry request must not leave a fresh SBOM beside an old lock.
    const pins = readConstraints(constraintsPath);
    const resolved = [];
    for (const pin of pins) {
        resolved.push(await resolvePin(pin));
    }
    const renderedSbom = `${JSON.stringify(sbom, null, 2)}\n`;
    const renderedLock = renderPylock(resolved, generatedAt);

    fs.writeFileSync(path.join(buildDir, SBOM_NAME), renderedSbom, 'utf8');
    fs.writeFileSync(path.join(buildDir, LOCK_NAME), renderedLock, 'utf8');

    const wheelCount = resolved.reduce((total, pkg) => total + pkg.wheels.length, 0);
    console.log(
        `Release provenance written for ${COMPANION_EXE_NAME} (SHA-256 ${artifactSha256}):\n` +
        `  ${path.join(buildDir, SBOM_NAME)}: CycloneDX ${CYCLONEDX_SPEC}, ${sbom.components.length} components\n` +
        `  ${path.join(buildDir, LOCK_NAME)}: PEP 751, ${resolved.length} packages, ${wheelCount} hashed wheels`
    );
    return { artifactSha256, sbom, resolved };
}

if (require.main === module) {
    writeReleaseProvenance().catch((error) => {
        console.error(`[write-release-provenance] ${error.message}`);
        process.exitCode = 1;
    });
}

module.exports = {
    LOCK_NAME,
    RESOLVE_COOLDOWN,
    SBOM_NAME,
    buildCycloneDx,
    readConstraints,
    renderPylock,
    sbomDescribesArtifact,
    uuidFromDigest,
    writeReleaseProvenance,
};
